def tables_lean(rchain):
    """`Tables.lean`; returns (text, manifest)."""
    man = []
    L = [HEADER, "import SaltC1.Cert54.Checks\n", TABLES_DOC, TABLES_LEMMAS]

    def thm(name, stmt):
        man.append((name, stmt))
        L.append("theorem %s : %s := by decide +kernel\n" % (name, stmt))
    L.append("\n/-! ## The factorial table and the series' constant terms -/\n\n")
    thm("fact_ok", "checkFact = true")
    thm("p54_zero", "p54T.findB 0 = 1")
    thm("p53_zero", "p53T.findB 0 = 1")
    fams = [("g46", "checkG gT46", 46, "g"), ("g48", "checkG gT48", 48, "g"),
            ("rec54", "checkRecGen p54T gT46 54", 46, "rec"), ("rec53", "checkRecGen p53T gT48 53", 48, "rec")]
    for fam, f, w, kind in fams:
        sh = plan_keys(w, kind)
        names = []
        L.append("\n/-! ## `%s` over the keys of weight `≤ %d`: %d shards -/\n\n" % (f, w, len(sh)))
        for k, (lo, hi, s, n) in enumerate(sh):
            nm = "%s_ok_%d" % (fam, k)
            names.append(nm)
            thm(nm, "checkAllL (%s) (%s) = true" % (f, _piece_list("keysRange %d %d %d" % (w, lo, hi), s, n)))
        top = w // 2 + 1
        L.append("\n/-- `%s` on every key of weight `≤ %d`, from the shards. -/\n" % (f, w))
        L.append("theorem %s_ok : checkAllL (%s) (keysW 13 %d) = true := by\n" % (fam, f, w))
        L.append("  rw [keysW_eq_keysRange %d %d rfl]\n  exact %s\n" % (
            w, top, _assemble(sh, names, None, top, None, "checkAllL_keysRange_append", "%d " % w)))
    for fam, f, w, R in (("wi", "checkWI WItree", 46, "wiEntriesR"), ("wj", "checkWJ WJtree", 48, "wjEntriesR")):
        sh = plan_entries(w)
        names = []
        L.append("\n/-! ## `%s` on the entries of weight `≤ %d`: %d shards -/\n\n" % (f, w, len(sh)))
        for k, (lo, hi, s, n) in enumerate(sh):
            nm = "%s_ok_%d" % (fam, k)
            names.append(nm)
            thm(nm, "checkAllL (%s) (%s) = true" % (f, _piece_list("%s %d %d" % (R, lo, hi), s, n)))
        top = w // 2 + 1
        whole = "wiEntries" if fam == "wi" else "wjEntries"
        L.append("\n/-- `%s` on all of `%s`, from the shards. -/\n" % (f, whole))
        L.append("theorem %s_ok : checkAllL (%s) %s = true := by\n" % (fam, f, whole))
        L.append("  rw [%s_eq_R]\n  exact %s\n" % (whole, _assemble(
            sh, names, None, top, None, "checkAllL_%s_append" % R, "")))
    L.append("\n/-! ## The collected marginal, three chained links (E3-3, E3-9) -/\n\n")
    for n, (p0, k0, p1, k1, cnt) in enumerate(rchain):
        thm("w_ok_%d" % n, "checkWChain wsh%d %d %d = (true, %d, %d, %d)" % (n, p0, k0, p1, k1, cnt))
    thm("w_close", "%d = nW ∧ %s = expectedLen" % (rchain[-1][2], " + ".join(str(c[4]) for c in rchain)))
    L.append(W_OK % dict(P1=rchain[0][2], K1=rchain[0][3], P2=rchain[1][2], K2=rchain[1][3],
                         P3=rchain[2][2], K3=rchain[2][3], C0=rchain[0][4], C1=rchain[1][4], C2=rchain[2][4]))
    L.append("\nend SaltC1.Cert54\n")
    return "".join(L), man



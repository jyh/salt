def audit_lean(texts):
    """`Audit.lean`: `#print axioms` on every theorem of the given module texts (the CI arm)."""
    import re
    names = [n for t in texts for n in re.findall(r"^theorem (\S+)", t, re.M)]
    body = "".join("#print axioms SaltC1.Cert54.%s\n" % n for n in names)
    return HEADER + AUDIT_DOC % len(names) + body, names



"""The Lean text of the k = 54 certificate's theorems: `Tables.lean`, `Forms.lean`, `Coeffs.lean`.

Called by `emit_cert54.py --write-lean SaltC1/Cert54`. Every kernel theorem here is one SHARD of a
check, sized by a cost model so that its kernel check stays near 3 GB of resident memory: the kernel's
memory grows with the work one declaration does (keys generated, recurrence box elements, table
entries, form pairs), not with the data, so each check is cut into theorems by that count. The
whole-list theorems (`rec54_ok : checkAllL … (keysW 13 46) = true`, `wi_ok`, …) are then DERIVED from
the shards by list lemmas, never re-run. The cost model's coefficients (GB above the process baseline,
per 1,000 elements) were measured one theorem per process:

  keys generated by `keysW`/`keysRange` 0.45 · `checkG` keys 0.26 · WI/WJ entries checked 0.37
  (entries generated 0.05) · form pairs 0.205 · the recurrence, fitted over its first 140 shards:
  keys generated 0.55 + box elements 0.19 + keys checked 0.97

Nothing here bears on twin primes.
"""
from math import prod

import c1series

BUDGET = 1.30          # GB above the baseline, per theorem
PAIRS = 6300           # form pairs per theorem (0.205 GB per 1,000)


def _cost_keys(gen, box, keys, per_key):
    return 0.45 * gen / 1000 + 0.25 * box / 1000 + per_key * keys / 1000


def plan_keys(w, kind):
    """Shards of the keys of weight <= w, as (lo, hi, s, n): `n is None` means `.drop s` (to the end of
    the block); `s is None` means the whole block `keysRange w lo hi`."""
    ks = c1series.keys_upto(13, w)
    blocks = []
    for v in range(w // 2 + 1):
        sub = [C for C in ks if C[0] == v]
        blocks.append([prod(c + 1 for c in C) for C in sub])

    def cost(gen, bx, nk):
        if kind == "rec":
            return (0.55 * gen + 0.19 * bx + 0.97 * nk) / 1000
        return _cost_keys(gen, 0, nk, 0.26)
    out = []
    v = 0
    while v <= w // 2:
        b = blocks[v]
        if cost(len(b), sum(b), len(b)) <= BUDGET:
            hi, gen, bx = v + 1, len(b), sum(b)
            while hi <= w // 2:
                nb = blocks[hi]
                if cost(gen + len(nb), bx + sum(nb), gen + len(nb)) > BUDGET:
                    break
                gen, bx, hi = gen + len(nb), bx + sum(nb), hi + 1
            out.append((v, hi, None, None))
            v = hi
            continue
        s = 0
        while s < len(b):
            n = 0
            while s + n < len(b) and cost(s + n + 1, sum(b[s:s + n + 1]), n + 1) <= BUDGET:
                n += 1
            assert n > 0, ("a single key exceeds the budget", w, v, s)
            out.append((v, v + 1, s, None if s + n == len(b) else n))
            s += n
        v += 1
    return out


def plan_entries(w):
    """Shards of `wiEntriesR`/`wjEntriesR` (w = 46/48), same shape as `plan_keys`."""
    ks = c1series.keys_upto(13, w)
    blocks = []
    for v in range(w // 2 + 1):
        blocks.append([w + 1 - c1series.weight(C) for C in ks if C[0] == v])   # entries per key

    def cost(keys, gen_entries, entries):
        return 0.45 * keys / 1000 + 0.05 * gen_entries / 1000 + 0.37 * entries / 1000
    out = []
    v = 0
    while v <= w // 2:
        b = blocks[v]
        if cost(len(b), sum(b), sum(b)) <= BUDGET:
            hi, nk, ne = v + 1, len(b), sum(b)
            while hi <= w // 2:
                nb = blocks[hi]
                if cost(nk + len(nb), ne + sum(nb), ne + sum(nb)) > BUDGET:
                    break
                nk, ne, hi = nk + len(nb), ne + sum(nb), hi + 1
            out.append((v, hi, None, None))
            v = hi
            continue
        # split the block by ENTRY offsets (the list is `wiEntriesR v (v+1)`)
        tot = sum(b)
        cum = [0]
        for e in b:
            cum.append(cum[-1] + e)
        s = 0
        while s < tot:
            n = 0
            step = 50
            while s + n < tot:
                n2 = min(n + step, tot - s)
                keys_gen = next(i for i in range(len(cum)) if cum[i] >= s + n2)
                if cost(keys_gen, s + n2, n2) > BUDGET:
                    break
                n = n2
            assert n > 0
            out.append((v, v + 1, s, None if s + n == tot else n))
            s += n
        v += 1
    return out


def plan_rows(N):
    out, lo = [], 0
    while lo < N:
        hi, p = lo, 0
        while hi < N and p + (N - hi) <= PAIRS:
            p += N - hi
            hi += 1
        assert hi > lo
        out.append((lo, hi))
        lo = hi
    return out


def _piece_list(base, s, n):
    if s is None:
        return base
    if n is None:
        return "(%s).drop %d" % (base, s)
    return "((%s).drop %d).take %d" % (base, s, n)


def _assemble(shards, names, wlist, top, block_base, append_lemma, w):
    """A term proving `checkAllL f (<block_base 0 top>) = true` from the shard theorems."""
    # group shard indices by block (lo, hi)
    groups = []
    for idx, (lo, hi, s, n) in enumerate(shards):
        if groups and groups[-1][0] == (lo, hi):
            groups[-1][1].append(idx)
        else:
            groups.append(((lo, hi), [idx]))
    assert groups[0][0][0] == 0 and groups[-1][0][1] == top

    def block_term(g):
        (lo, hi), idxs = g
        if shards[idxs[0]][2] is None:
            assert len(idxs) == 1
            return names[idxs[0]]
        # the drop chain, from the last piece back to drop 0, then `List.drop_zero`
        term = names[idxs[-1]]
        for i in reversed(idxs[:-1]):
            _, _, s, n = shards[i]
            term = "checkAllL_drop_of _ _ %d %d %s (%s)" % (s, n, names[i], term)
        return "checkAllL_of_drop_zero (%s)" % term

    term = "(%s)" % block_term(groups[-1])
    for g in reversed(groups[:-1]):
        (lo, hi), _ = g
        term = "(%s _ %s%d %d %d (by omega) (by omega) (%s)\n    %s)" % (
            append_lemma, w, lo, hi, top, block_term(g), term)
    return term



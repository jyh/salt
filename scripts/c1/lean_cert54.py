def forms_lean(r, coef_n):
    """`Forms.lean`; returns (text, manifest)."""
    man = []
    L = [HEADER, "import SaltC1.Cert54.Checks\nimport Mathlib.Data.Nat.Factorial.Basic\n"
         "import Mathlib.Tactic.NormNum\n", FORMS_DOC]

    def thm(name, stmt):
        man.append((name, stmt))
        L.append("theorem %s : %s := by decide +kernel\n" % (name, stmt))
    rows = {"I": r["rowI"], "J": r["rowJ"]}
    blocks = {}
    for nm, N in (("I", coef_n), ("J", len(r["W"]))):
        bl = plan_rows(N)
        blocks[nm] = bl
        L.append("\n/-! ## `%shalf`, %d blocks of at most %d pairs -/\n\n" % (nm, len(bl), PAIRS))
        for lo, hi in bl:
            thm("%shalf_%d_%d" % (nm, lo, hi), "%shalf %d %d = %d" % (nm, lo, hi, sum(rows[nm][lo:hi])))
    from math import factorial
    for nm in ("I", "J"):
        bl = blocks[nm]
        L.append("\n/-- The %s form at the common scale: the sum of its blocks. -/\n" % nm)
        L.append("noncomputable def %sint : Int :=\n  " % nm + " +\n  ".join(
            "%shalf %d %d" % (nm, lo, hi) for lo, hi in bl) + "\n")
        L.append("\ntheorem %sint_eq : %sint = %d := by\n  rw [%sint, " % (nm, nm, r[nm + "int"], nm)
                 + ", ".join("%shalf_%d_%d" % (nm, lo, hi) for lo, hi in bl) + "]\n  norm_num\n")
    L.append(FORMS_TAIL % (factorial(100), factorial(24) ** 2 * factorial(101)))
    man.append(("F100_eq", "F100 = Nat.factorial 100"))
    man.append(("Dconst_eq", "Dconst = Nat.factorial 24 ^ 2 * Nat.factorial 101"))
    return "".join(L), man


